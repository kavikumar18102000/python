#Numeric operators
print(2 + 5)
print(5 - 2)
print(2 * 5)
print(5 / 2)
print(5 // 2) #floor division - It divides two numbers and rounds down the quotient(to int)
print(5 % 2) #remainder of the division(leftover part after division)
print(2 ** 3) #exponentiation - it raises a number to the power of another number(2 * 2* 2 = 2**3)

#assignment(=) operator
a = 10
b = 20
print(a + b)

#increment or decrement(python does not traditional ++ or -- like in c, java, c++..)
a += 10
print(a)
a -= 1
print(a)

a *= 2
print(a)
a /= 2
print(a)
a %= 2
print(a)